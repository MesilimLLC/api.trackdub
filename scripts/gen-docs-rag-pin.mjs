// Generate src/docs-rag/pin.generated.ts from Trackdub's runtime/trt-rtx-ep.manifest.json so the
// pin the Worker states to agents cannot drift from the bundle Trackdub ships.
//   node scripts/gen-docs-rag-pin.mjs           write the file (runs before dev/deploy)
//   node scripts/gen-docs-rag-pin.mjs --check   exit 1 when the committed file is stale
// TRACKDUB_ROOT overrides the sibling checkout (default: ../Trackdub).
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "src", "docs-rag", "pin.generated.ts");
const manifestPath = path.join(
  process.env.TRACKDUB_ROOT ?? path.join(root, "..", "Trackdub"),
  "runtime",
  "trt-rtx-ep.manifest.json",
);
const check = process.argv.includes("--check");

if (!existsSync(manifestPath)) {
  console.warn(`pin: ${manifestPath} not found; keeping the committed pin.generated.ts (set TRACKDUB_ROOT to regenerate)`);
  process.exit(0);
}

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const versionOf = (platform) =>
  manifest.packages?.[platform]?.archiveUrl?.match(/\/v(\d+\.\d+\.\d+)\//)?.[1] ?? manifest.version;
const windows = versionOf("win-x64");
const linux = versionOf("linux-x64");
const abi = windows === linux ? `${windows} (Windows and Linux)` : `${windows} (Windows) / ${linux} (Linux)`;
const sentence = `Trackdub pins TensorRT-RTX EP ABI ${abi}, CUDA ${manifest.cudaVariant}, TensorRT-RTX ${manifest.trtRtxRuntimeVersion}.`;

const source = `// Generated by scripts/gen-docs-rag-pin.mjs from Trackdub runtime/trt-rtx-ep.manifest.json. Do not edit.
export const PIN = {
  windows: ${JSON.stringify(windows)},
  linux: ${JSON.stringify(linux)},
  cuda: ${JSON.stringify(manifest.cudaVariant)},
  trtRtx: ${JSON.stringify(manifest.trtRtxRuntimeVersion)},
} as const;

export const PIN_SENTENCE = ${JSON.stringify(sentence)};
`;

const current = existsSync(output) ? await readFile(output, "utf8") : "";
if (check) {
  if (current !== source) {
    console.error(`pin: ${path.relative(root, output)} is stale; run \`node scripts/gen-docs-rag-pin.mjs\``);
    process.exit(1);
  }
  console.log(`pin: up to date (${sentence})`);
} else if (current !== source) {
  await writeFile(output, source);
  console.log(`pin: wrote ${path.relative(root, output)} (${sentence})`);
} else {
  console.log("pin: unchanged");
}
